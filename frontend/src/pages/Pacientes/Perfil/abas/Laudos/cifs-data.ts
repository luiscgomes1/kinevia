export type ComponenteCIF = 'FUNCOES' | 'ESTRUTURAS' | 'ATIVIDADES' | 'AMBIENTAIS'

export interface ItemCIF {
    codigo: string
    descricao: string
    componente: ComponenteCIF
}

export const COMPONENTE_CIF_ROTULO: Record<ComponenteCIF, string> = {
    FUNCOES: 'Funções do corpo',
    ESTRUTURAS: 'Estruturas do corpo',
    ATIVIDADES: 'Atividades e participação',
    AMBIENTAIS: 'Fatores ambientais',
}

export function componenteDoCodigo(codigo: string): ComponenteCIF {
    const prefixo = codigo.trim().charAt(0).toLowerCase()
    if (prefixo === 'b') return 'FUNCOES'
    if (prefixo === 's') return 'ESTRUTURAS'
    if (prefixo === 'e') return 'AMBIENTAIS'
    return 'ATIVIDADES'
}

export function buscarItemCIF(codigo: string): ItemCIF | undefined {
    const alvo = codigo.trim().toLowerCase()
    return CIF_CODIGOS.find((i) => i.codigo.toLowerCase() === alvo)
}

